import { writeFileSync } from 'fs';
import { join } from 'path';

/**
 * Generate CSV report
 */
function generateCSV(results) {
  const headers = 'Date,Label,URL,Viewport,Tool,Rule ID,Impact/Severity,Selector,Help URL\n';
  const rows = [];

  for (const result of results) {
    if (result.axe?.violations) {
      for (const violation of result.axe.violations) {
        for (const node of violation.nodes) {
          rows.push([
            new Date(result.timestamp).toISOString(),
            '',
            result.url,
            result.viewport,
            'axe-core',
            violation.id,
            violation.impact,
            node.target.join(' > '),
            violation.helpUrl,
          ].join(','));
        }
      }
    }

    if (result.lighthouse?.audits) {
      for (const audit of result.lighthouse.audits) {
        rows.push([
          new Date(result.timestamp).toISOString(),
          '',
          result.url,
          result.viewport,
          'lighthouse',
          audit.id,
          Math.round((1 - audit.score) * 100) + '%',
          '',
          '',
        ].join(','));
      }
    }

    if (result.pa11y?.issues) {
      for (const issue of result.pa11y.issues) {
        rows.push([
          new Date(result.timestamp).toISOString(),
          '',
          result.url,
          result.viewport,
          'pa11y',
          issue.code,
          issue.type,
          issue.selector || '',
          '',
        ].join(','));
      }
    }
  }

  return headers + rows.join('\n');
}

/**
 * Analyze results for summary
 */
function analyzeResults(results) {
  const analysis = {
    totalScans: results.length,
    urlsScanned: new Set(results.map(r => r.url)).size,
    axeViolations: 0,
    axeViolationsByRule: {},
    axeViolationsByPage: {},
    axeViolationsByImpact: { critical: 0, serious: 0, moderate: 0, minor: 0 },
    lighthouseIssues: 0,
    pa11yIssues: 0,
    passed: true,
  };

  for (const result of results) {
    if (result.axe?.violations) {
      const violationCount = result.axe.violations.reduce((sum, v) => sum + v.nodes.length, 0);
      
      if (violationCount > 0) {
        analysis.passed = false;
        analysis.axeViolations += violationCount;
        
        const pageKey = `${result.url} (${result.viewport})`;
        analysis.axeViolationsByPage[pageKey] = violationCount;

        for (const violation of result.axe.violations) {
          analysis.axeViolationsByRule[violation.id] = 
            (analysis.axeViolationsByRule[violation.id] || 0) + violation.nodes.length;
          
          analysis.axeViolationsByImpact[violation.impact] += violation.nodes.length;
        }
      }
    }

    if (result.lighthouse?.audits) {
      analysis.lighthouseIssues += result.lighthouse.audits.length;
    }

    if (result.pa11y?.issues) {
      analysis.pa11yIssues += result.pa11y.issues.length;
    }
  }

  return analysis;
}

/**
 * Generate Markdown summary
 */
function generateMarkdown(analysis, metadata) {
  const status = analysis.passed ? '✓ PASS' : '✗ FAIL';
  const statusEmoji = analysis.passed ? '✓' : '✗';

  let md = `# ASR Accessibility Scan Report

## ${statusEmoji} ${status}

**Label:** ${metadata.label}  
**Scan Date:** ${new Date().toLocaleString()}  
**Source:** ${metadata.source}  
**URLs Scanned:** ${analysis.urlsScanned}  
**Total Scans:** ${analysis.totalScans} (${analysis.urlsScanned} URLs × 2 viewports)

---

## Summary

- **axe-core violations:** ${analysis.axeViolations} ${analysis.passed ? '' : '❌'}
- **Lighthouse issues:** ${analysis.lighthouseIssues} (informational)
- **pa11y issues:** ${analysis.pa11yIssues} (informational)

**Pass Rule:** Zero axe-core violations = PASS. Lighthouse and pa11y findings are reported but do not fail the scan.

### axe-core Violations by Impact

| Impact   | Count |
|----------|-------|
| Critical | ${analysis.axeViolationsByImpact.critical} |
| Serious  | ${analysis.axeViolationsByImpact.serious} |
| Moderate | ${analysis.axeViolationsByImpact.moderate} |
| Minor    | ${analysis.axeViolationsByImpact.minor} |

`;

  if (Object.keys(analysis.axeViolationsByPage).length > 0) {
    md += '### axe-core Violations by Page\n\n';
    md += '| Page | Violations |\n|------|------------|\n';
    for (const [page, count] of Object.entries(analysis.axeViolationsByPage).sort((a, b) => b[1] - a[1])) {
      md += `| ${page} | ${count} |\n`;
    }
    md += '\n';
  }

  if (Object.keys(analysis.axeViolationsByRule).length > 0) {
    md += '### axe-core Violations by Rule\n\n';
    md += '| Rule ID | Count |\n|---------|-------|\n';
    for (const [rule, count] of Object.entries(analysis.axeViolationsByRule).sort((a, b) => b[1] - a[1])) {
      md += `| ${rule} | ${count} |\n`;
    }
    md += '\n';
  }

  md += `---

*Generated by ASR Accessibility Scanner*  
*WCAG 2.2 Level AA compliance check*
`;

  return md;
}

