/**
 * Generate all reports
 */
export async function generateReports(results, metadata, runDir) {
  console.log('\nGenerating reports...');

  const analysis = analyzeResults(results);

  writeFileSync(join(runDir, 'results.csv'), generateCSV(results));
  console.log('  ✓ results.csv');

  const markdown = generateMarkdown(analysis, metadata);
  writeFileSync(join(runDir, 'summary.md'), markdown);
  console.log('  ✓ summary.md');

  const html = generateHTML(analysis, metadata);
  writeFileSync(join(runDir, 'summary.html'), html);
  console.log('  ✓ summary.html');

  console.log(`\n${analysis.passed ? '✓ PASS' : '✗ FAIL'}: ${analysis.axeViolations} axe-core violations found`);
  if (!analysis.passed) {
    console.log(`  Critical: ${analysis.axeViolationsByImpact.critical}, Serious: ${analysis.axeViolationsByImpact.serious}, Moderate: ${analysis.axeViolationsByImpact.moderate}, Minor: ${analysis.axeViolationsByImpact.minor}`);
  }
}
